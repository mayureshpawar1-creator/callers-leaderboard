// Time handling rules:
// - CDR dates/times are India Standard Time wall-clock values exactly as the dialer prints them.
//   They are stored as naive strings ("YYYY-MM-DD" / "YYYY-MM-DD HH:MM:SS") and never shifted.
// - System timestamps (uploaded_at, audit entries) are stored as UTC ISO strings and shown in IST.

export function nowUtcIso(): string {
  return new Date().toISOString();
}

export function isValidYmd(y: number, m: number, d: number): boolean {
  if (!Number.isInteger(y) || !Number.isInteger(m) || !Number.isInteger(d)) return false;
  if (y < 1900 || y > 2200 || m < 1 || m > 12 || d < 1) return false;
  const dim = new Date(Date.UTC(y, m, 0)).getUTCDate();
  return d <= dim;
}

export function ymd(y: number, m: number, d: number): string {
  return `${y}-${String(m).padStart(2, "0")}-${String(d).padStart(2, "0")}`;
}

export function hms(h: number, mi: number, s: number): string {
  return `${String(h).padStart(2, "0")}:${String(mi).padStart(2, "0")}:${String(s).padStart(2, "0")}`;
}

/** Format seconds as "2h 05m 09s". */
export function formatSeconds(total: number): string {
  const h = Math.floor(total / 3600);
  const m = Math.floor((total % 3600) / 60);
  const s = total % 60;
  return `${h}h ${String(m).padStart(2, "0")}m ${String(s).padStart(2, "0")}s`;
}
